/// Worldwide languages for the login page "Translate" picker.
///
/// Every entry has its ISO language code, its English name and its native
/// name. The list is deliberately comprehensive (120 languages) so a user
/// anywhere in the world finds their language. Selecting one sets the
/// login language through the same `_language` state the 8 quick chips
/// use — see [loginLabel]: for the 8 chip languages it returns the exact
/// chip string (so the chip highlights), otherwise the native name.
class AppLanguage {
  final String code; // ISO 639-1 (639-2 where no 639-1 exists)
  final String english; // English name, e.g. Spanish
  final String native; // native name, e.g. Español

  const AppLanguage(this.code, this.english, this.native);
}

/// The 8 quick-chip strings on the login page, by code.
const Map<String, String> kLoginChipLabels = {
  'en': 'English',
  'ur': 'Urdu',
  'ar': 'العربية',
  'id': 'Bahasa Indonesia',
  'tr': 'Türkçe',
  'fr': 'Français',
  'bn': 'বাংলা',
  'hi': 'हिन्दी',
};

/// Label to store in the login `_language` state for [lang].
String loginLabel(AppLanguage lang) =>
    kLoginChipLabels[lang.code] ?? lang.native;

